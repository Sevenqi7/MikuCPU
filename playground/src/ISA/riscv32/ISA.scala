object MkRV32Factory extends ISAFactory {
    type ExcepDefns = RV32ExceptionDefns.type
    type CSRDefns   = RV32CSRRegisters.type

    def isaName:            String           = "RISCV32-IMA"
    def getFetchUnit():     MkIFU            = new RV32IFU
    def getDecoder():       DecoderUnit      = new RV32DecoderUnit
    def getOperandGen():    OperandGenerator = new RV32OperandGen
    def getExcepDefns():    ExcepDefns       = RV32ExceptionDefns
    def getExcepInfo():     ExceptionInfo    = new RV32ExceptionInfo
    def getDecodedInst():   DecodedInst      = new RV32DecodedInst
    def getLoadStoreUnit(): MkLSU            = new RV32LSU
    def getBranchUnit():    MkBRU            = new RV32BranchUnit
    def getMiscFu():        MiscFunctionUnit = new RV32MiscFu
    def getCSRDefns():      CSRDefns         = RV32CSRRegisters
    def getCSRBuffer():     CSRBuffer        = new RV32CSRBuffer
    def getCSRRegfiles():   CSRRegfiles      = new RV32CSRRegfiles

    override def isBr(inst: UInt):       Bool = inst(6, 0) === "b1100011".U || isUncondBr(inst)
    override def isUncondBr(inst: UInt): Bool =
        inst(14, 12) === 0.U && inst(6, 4) === "b110".U && inst(2, 0) === "b011".U

    val RESET_VECTOR  = 0x80000000 - 4
    val CSR_ADDR_WD   = 12
    val EXCP_RET_INST = MiscOpType.ertn.litValue.toInt
}

class RV32DecodedInst extends DecodedInst {
    def getRs2(raw_inst: UInt): UInt = raw_inst(24, 20)
    def getRs1(raw_inst: UInt): UInt = raw_inst(19, 15)
    def getRd(raw_inst: UInt):  UInt = raw_inst(11, 7)
}

